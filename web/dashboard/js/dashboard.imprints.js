window.navigateWizard = async (delta) => {
    const currentStep = window.currentImprintWizardStep || 1;
    const targetStep = currentStep + delta;
    
    if (delta > 0) {
        // 校验当前步骤
        if (currentStep === 1) {
            const pathInput = document.getElementById('wiz-vault-path');
            const idVal = (document.getElementById('wiz-imprint-id')?.value || 'my_notes').trim();
            if (pathInput && !pathInput.value.trim()) {
                pathInput.value = `./manuscripts/${idVal}`;
            }
        } else if (currentStep === 2) {
            const idInput = document.getElementById('wiz-imprint-id');
            const nameInput = document.getElementById('wiz-imprint-name');
            const errId = document.getElementById('wiz-error-id');
            const errName = document.getElementById('wiz-error-name');
            
            const idVal = idInput ? idInput.value.trim() : '';
            const nameVal = nameInput ? nameInput.value.trim() : '';
            
            let hasError = false;
            
            const existing = window._existingImprintList || [];
            
            if (!nameVal) {
                if (errName) {
                    errName.innerHTML = '⚠️ <b>请填写品牌展示名称</b>';
                    errName.style.display = 'block';
                }
                if (nameInput) nameInput.classList.add('input-error');
                hasError = true;
            } else if (existing.some(imp => (imp.name || imp.press_name || '').toLowerCase() === nameVal.toLowerCase())) {
                if (errName) {
                    errName.innerHTML = '⚠️ <b>品牌名称已被占用</b>，请换一个名称';
                    errName.style.display = 'block';
                }
                if (nameInput) nameInput.classList.add('input-error');
                hasError = true;
            }
            
            const RESERVED_IMPRINT_IDS = ['default', 'global', 'system', 'admin', 'api', 'dashboard', 'configs', 'themes', 'plugins'];

            if (!idVal) {
                if (errId) {
                    errId.innerHTML = '⚠️ <b>品牌唯一标识 (ID) 不能为空</b>';
                    errId.style.display = 'block';
                }
                if (idInput) idInput.classList.add('input-error');
                hasError = true;
            } else if (!/^[a-zA-Z0-9_-]+$/.test(idVal)) {
                if (errId) {
                    errId.innerHTML = '⚠️ <b>格式不合法</b>：仅支持英文、数字与下划线';
                    errId.style.display = 'block';
                }
                if (idInput) idInput.classList.add('input-error');
                hasError = true;
            } else if (RESERVED_IMPRINT_IDS.includes(idVal.toLowerCase())) {
                if (errId) {
                    errId.innerHTML = `⚠️ <b>'${idVal}' 为系统保留标识</b>，请自定义品牌 ID`;
                    errId.style.display = 'block';
                }
                if (idInput) idInput.classList.add('input-error');
                hasError = true;
            } else if (existing.some(imp => (imp.id || imp.name || '').toLowerCase() === idVal.toLowerCase())) {
                if (errId) {
                    errId.innerHTML = '⚠️ <b>品牌标识 (ID) 已存在</b>，请换一个标识';
                    errId.style.display = 'block';
                }
                if (idInput) idInput.classList.add('input-error');
                hasError = true;
            }
            
            if (hasError) return;
        } else if (currentStep === 3) {
            // 步骤 3 点击右下角按钮直接提交创建并展示成功就绪页
            await window.submitImprintWizard();
            return;
        }
    }
    
    if (targetStep >= 1 && targetStep <= 3) {
        window.updateWizardStepView(targetStep);
    }
};

