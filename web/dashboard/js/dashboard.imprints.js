// 🔤 极简高效的中文首字母/拼音快速转换辅助，用于智能 ID Slug 生成
window.generateSlugFromTitle = (title) => {
    if (!title) return '';
    const clean = title.trim().toLowerCase();
    // 过滤特殊字符
    let slug = clean
        .replace(/[^\w\u4e00-\u9fa5\s-]+/g, '')
        .replace(/[\s-]+/g, '_')
        .replace(/^_+|_+$/g, '');
    
    // 若纯英文/数字，直接返回
    if (/^[a-z0-9_]+$/.test(slug)) return slug;
    
    // 若含中文，生成带时间戳或前缀的稳健标识
    const latinPart = slug.replace(/[\u4e00-\u9fa5]/g, '').replace(/^_+|_+$/g, '');
    if (latinPart) return latinPart;
    
    return 'imprint_' + Math.random().toString(36).substring(2, 7);
};

